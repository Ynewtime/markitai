// Package the built workbench for another backend (Python markitai vendors it):
// a reproducible tar.gz holding index.html, every file served under /ui/ (the
// built bundle, the vendored modules and font) and their licences, plus a
// manifest with the source commit, each file's size and SHA-256, the build
// command, the Content Security Policy and the paths that serve the page.
//
//   node scripts/package.mjs OUTDIR [--allow-dirty]
//
// It refuses a dist/ that does not match its sources (`node build.mjs --check`)
// and, without --allow-dirty, a working tree with uncommitted workbench changes.
// The archive is byte-for-byte reproducible: entries sorted at the archive
// root, owner 0, mode 0644, mtime of the source commit, gzip without a
// timestamp.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(web, "../../../../..");
const dist = join(web, "dist");
const vendor = join(root, "vendor/web");
const args = process.argv.slice(2);
const out = args.find((arg) => !arg.startsWith("--"));
if (!out) {
  console.error("usage: node scripts/package.mjs OUTDIR [--allow-dirty]");
  process.exit(2);
}
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const git = (...command) => execFileSync("git", command, { cwd: root, encoding: "utf8" }).trim();

execFileSync(process.execPath, ["build.mjs", "--check"], { cwd: web, stdio: "inherit" });
const dirty = git("status", "--porcelain", "--", "crates/markitai-cli/src/server/web", "vendor/web");
if (dirty && !args.includes("--allow-dirty")) {
  console.error(`uncommitted workbench changes; commit them first:\n${dirty}`);
  process.exit(1);
}
const commit = git("rev-parse", "HEAD");
const committed = Number(git("show", "-s", "--format=%ct", "HEAD"));
const built = JSON.parse(readFileSync(join(dist, "manifest.json"), "utf8"));
const version = JSON.parse(readFileSync(join(web, "package.json"), "utf8")).version;

/** Archive path → bytes. Everything a browser fetches lives under ui/. */
const files = new Map();
files.set("index.html", readFileSync(join(dist, "index.html")));
for (const name of Object.keys(built.files).sort()) {
  if (name === "index.html") continue;
  files.set(`ui/${name}`, readFileSync(join(dist, name)));
}
// Plain copies of what dist/ keeps only compressed, and the font the page preloads.
files.set("ui/marked.js", readFileSync(join(vendor, "marked.js")));
files.set("ui/purify.js", readFileSync(join(vendor, "purify.js")));
for (const subset of ["latin", "latin-ext", "cyrillic", "cyrillic-ext", "greek", "greek-ext", "vietnamese"]) {
  files.set(`ui/inter-${subset}-wght.woff2`, readFileSync(join(vendor, `inter-${subset}-wght-normal.woff2`)));
}
for (const name of ["marked-LICENSE", "DOMPurify-LICENSE", "Inter-OFL.txt", "phosphor-LICENSE", "preact-LICENSE"]) {
  files.set(`LICENSES/${name}`, readFileSync(join(vendor, name)));
}

const csp = /const CSP: &str = "([^"]+)";/.exec(readFileSync(join(web, "../web.rs"), "utf8"))?.[1];
if (!csp) throw new Error("web.rs no longer declares the CSP");
const manifest = {
  note: "Generated by scripts/package.mjs; do not edit. Serve index.html at every page path and ui/<name> at /ui/<name>.",
  name: "markitai-workbench",
  version,
  source_commit: commit,
  build_command: "cd crates/markitai-cli/src/server/web && npm ci && node build.mjs && node scripts/package.mjs OUTDIR",
  source: { repository: "Ynewtime/markitai-rust", commit, committed_at: new Date(committed * 1000).toISOString(), dirty: Boolean(dirty) },
  build: {
    command: "cd crates/markitai-cli/src/server/web && npm ci && node build.mjs && node scripts/package.mjs OUTDIR",
    source_digest: built.source_digest,
    tools: built.tools,
    node: process.version,
  },
  serve: {
    page_paths: ["/", "/jobs", "/settings", "/settings/models", "/settings/appearance", "/settings/access"],
    asset_prefix: "/ui/",
    content_security_policy: csp,
    headers: { "X-Content-Type-Options": "nosniff", "Referrer-Policy": "no-referrer", "Cache-Control": "no-cache" },
    gzip_twins: [...files.keys()].filter((name) => name.endsWith(".gz")).map((name) => name.slice(3, -3)),
    api_contract: "API-CONTRACT.md version 1.1",
  },
  files: Object.fromEntries([...files].map(([name, bytes]) => [name, { bytes: bytes.length, sha256: sha256(bytes) }])),
};
const manifestBytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`);
files.set("manifest.json", manifestBytes);

/** One ustar header block. */
function header(name, size, mtime) {
  const block = Buffer.alloc(512);
  const field = (offset, length, value) => block.write(value, offset, length, "ascii");
  const octal = (offset, length, value) => field(offset, length, `${value.toString(8).padStart(length - 1, "0")}\0`);
  if (Buffer.byteLength(name) > 100) throw new Error(`name too long for ustar: ${name}`);
  block.write(name, 0, 100, "utf8");
  octal(100, 8, 0o644);
  octal(108, 8, 0);
  octal(116, 8, 0);
  octal(124, 12, size);
  octal(136, 12, mtime);
  block.fill(" ", 148, 156);
  field(156, 1, "0");
  field(257, 6, "ustar\0");
  field(263, 2, "00");
  field(265, 32, "root");
  field(297, 32, "root");
  let sum = 0;
  for (const byte of block) sum += byte;
  octal(148, 7, sum);
  block[155] = 0x20;
  return block;
}

const prefix = `markitai-workbench-${version}-${commit.slice(0, 12)}`;
const chunks = [];
for (const name of [...files.keys()].sort()) {
  const bytes = files.get(name);
  chunks.push(header(name, bytes.length, committed), bytes, Buffer.alloc((512 - (bytes.length % 512)) % 512));
}
chunks.push(Buffer.alloc(1024));
const archive = gzipSync(Buffer.concat(chunks), { level: 9 });
archive[9] = 0xff; // "unknown" OS byte, as build.mjs does; the header mtime is already zero

mkdirSync(out, { recursive: true });
const archiveName = `${prefix}.tar.gz`;
writeFileSync(join(out, archiveName), archive);
writeFileSync(join(out, `${prefix}.manifest.json`), manifestBytes);
// The latest build, under fixed names, and a history of every published build.
writeFileSync(join(out, "latest.tar.gz"), archive);
writeFileSync(join(out, "latest.manifest.json"), manifestBytes);
const historyPath = join(out, "history.json");
const history = existsSync(historyPath) ? JSON.parse(readFileSync(historyPath, "utf8")) : [];
const entry = { archive: archiveName, sha256: sha256(archive), bytes: archive.length, commit, dirty: Boolean(dirty), source_digest: built.source_digest, packaged_at: new Date().toISOString() };
if (!history.some((known) => known.sha256 === entry.sha256)) history.push(entry);
writeFileSync(historyPath, `${JSON.stringify(history, null, 2)}\n`);
console.log(`${archiveName} · ${archive.length} B · sha256 ${entry.sha256}`);
