// Provider names are proper nouns; only the generic labels are translated.
export function providerName(provider) {
  if (provider?.provider === 'custom') return t('providerCustom');
  if (!provider?.label || provider.label === 'Unknown provider') return provider?.provider ? `${t('providerUnknown')} (${provider.provider})` : t('providerUnknown');
  return provider.label;
}

// Browser-only helpers below.
export function translatePage(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    for (const node of root.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
}
