const message = (key, values, detail) => ({text: t(key, values), detail});
function shaped(text, shapes, kind) {
  for (const [pattern, pick] of shapes) {
    const match = pattern.exec(text);
    if (match) { const [key, values] = pick(match, kind); return message(key, values, text); }
  }
  return null;
}
// Every dictionary key the tables above can produce, for the dictionary tests.
export function messageKeys() {
  const keys = new Set([...Object.values(API_REASONS), ...Object.values(API_CODES), ...Object.values(ITEM_CODES), ...Object.values(PERSISTENCE), ...Object.values(MODEL_REASONS)]);
  for (const prefix of ['errPage', 'errModel']) for (const kind of HTTP_KINDS) keys.add(prefix + kind);
  for (const shapes of [ITEM_SHAPES, NOTE_SHAPES]) for (const [, pick] of shapes) for (const kind of ['file', 'url']) keys.add(pick(['', '200'], kind)[0]);
  return [...keys];
}
export function apiErrorMessage(status, body) {
  const structured = body?.detail && typeof body.detail === 'object' ? String(body.detail.code || '') : '';
  const original = typeof body?.detail === 'string' ? body.detail : structured;
  const key = API_REASONS[body?.reason] || API_REASONS[structured] || API_CODES[body?.code];
  if (key) return message(key, undefined, original);
  return {text: original || t('requestFailed', {status}), detail: ''};
}
// A failed item's error. `hint` marks a stop or shutdown, which is not a fault;
// `formats` is the folded extension list of an unsupported-format message.
export function itemErrorMessage(item) {
  const text = typeof item?.error === 'string' ? item.error : '', code = item?.error_code;
  if (code === 'cancelled' || text === 'cancelled (stopped by request)') return {text: t('itemStopped'), detail: '', hint: true};
  if (code === 'shutdown' || text === 'cancelled (server shutdown)') return {text: t('itemShutdown'), detail: '', hint: true};
  const split = text.indexOf(' Supported extensions:');
  const head = split > 0 ? text.slice(0, split) : text;
  const formats = split > 0 ? text.slice(split + 1).replace(/^Supported extensions:\s*/, '').replace(/\.$/, '') : '';
  const unsupported = /^Unsupported file format: (.+)\.$/.exec(head);
  if (unsupported) return {text: t('unsupportedFormat', {format: unsupported[1]}), detail: '', formats};
  const result = shaped(head, ITEM_SHAPES, item?.kind) || (ITEM_CODES[code] ? message(ITEM_CODES[code], undefined, text) : {text, detail: ''});
  return {...result, detail: result.detail ? text : '', formats};
}
// Provider probe and discovery details, which the core words as fixed English text.
export function serviceNote(text) {
  if (typeof text !== 'string' || !text) return {text: '', detail: ''};
  return shaped(text, NOTE_SHAPES) || {text, detail: ''};
}
export function persistenceMessage(text) {
  return PERSISTENCE[text] ? message(PERSISTENCE[text], undefined, text) : {text, detail: ''};
}
