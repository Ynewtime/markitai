export const DICTIONARIES = Object.freeze({en, zh});
let locale = 'en';

function storage() { try { return globalThis.localStorage ?? null; } catch { return null; } }
function read(key) { try { return storage()?.getItem(key) ?? null; } catch { return null; } }
function write(key, value) { try { value === null ? storage()?.removeItem(key) : storage()?.setItem(key, value); } catch { /* Preference stays for this page only. */ } }

// An explicit choice wins; otherwise the browser's first language decides.
export function detectLocale(stored = read(LANG_KEY), language = globalThis.navigator?.language) {
  if (LOCALES.includes(stored)) return stored;
  return String(language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export function currentLocale() { return locale; }
// Plural keys use `_one`/`_other`; Chinese repeats the same text for both.
export function t(key, values) {
  const table = DICTIONARIES[locale] || en;
  let name = key;
  if (values && typeof values.count === 'number') name = `${key}_${values.count === 1 ? 'one' : 'other'}`;
  const text = table[name] ?? table[key] ?? en[name] ?? en[key] ?? key;
  return values ? text.replace(/\{(\w+)\}/g, (match, field) => field in values ? String(values[field]) : match) : text;
}
export function useLocale(value) { locale = LOCALES.includes(value) ? value : 'en'; return locale; }

// Browser-only helpers below.
export function translatePage(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    for (const node of root.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
}
export function setLocale(value, {persist = true} = {}) {
  useLocale(value);
  if (persist) write(LANG_KEY, locale);
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  translatePage();
  for (const node of document.querySelectorAll('[data-lang]')) node.setAttribute('aria-pressed', String(node.dataset.lang === locale));
  window.dispatchEvent(new CustomEvent('markitai:locale', {detail: locale}));
}
export function themePreference() { const value = read(THEME_KEY); return THEMES.includes(value) ? value : 'auto'; }
const THEME_ICONS = {auto: '◐', light: '☀', dark: '☾'};
export function setTheme(value, {persist = true} = {}) {
  const mode = THEMES.includes(value) ? value : 'auto';
  if (mode === 'auto') document.documentElement.removeAttribute('data-theme'); else document.documentElement.dataset.theme = mode;
  if (persist) write(THEME_KEY, mode === 'auto' ? null : mode);
  const toggle = document.getElementById('theme-toggle');
  if (toggle) {
    const text = t('themeButton', {mode: t({auto: 'themeAuto', light: 'themeLight', dark: 'themeDark'}[mode])});
    toggle.dataset.mode = mode; toggle.textContent = THEME_ICONS[mode]; toggle.setAttribute('aria-label', text); toggle.title = text;
  }
}
export function nextTheme(mode) { return THEMES[(THEMES.indexOf(mode) + 1) % THEMES.length]; }
